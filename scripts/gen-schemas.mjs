// Generate TypeScript types (web) and Pydantic models (api) from /shared/schemas.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "shared", "schemas");
const tsOut = join(root, "web", "src", "types", "generated");
const pyOut = join(root, "api", "app", "schemas", "generated");
mkdirSync(tsOut, { recursive: true });
mkdirSync(pyOut, { recursive: true });

// datamodel-codegen cannot write cross-file $refs to a single file, so inline them as $defs.
function bundle(file, defs = {}) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  const walk = (node) => {
    if (Array.isArray(node)) return node.map(walk);
    if (node && typeof node === "object") {
      return Object.fromEntries(
        Object.entries(node).map(([k, v]) => {
          if (k === "$ref" && typeof v === "string" && v.endsWith(".schema.json")) {
            const target = JSON.parse(readFileSync(join(schemaDir, v), "utf8"));
            if (!defs[target.title]) {
              defs[target.title] = {};
              const inner = bundle(v, defs);
              delete inner.$defs;
              delete inner.$id; // embedded $id values change how local refs resolve
              delete inner.$schema;
              defs[target.title] = inner;
            }
            return [k, `#/$defs/${target.title}`];
          }
          return [k, walk(v)];
        }),
      );
    }
    return node;
  };
  const out = walk(schema);
  if (Object.keys(defs).length) out.$defs = { ...(out.$defs ?? {}), ...defs };
  return out;
}

const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json"));
for (const file of files) {
  const base = file.replace(".schema.json", "");
  const ts = await compileFromFile(join(schemaDir, file), { bannerComment: "/* Generated by `pnpm schemas`. Do not edit. */" });
  writeFileSync(join(tsOut, `${base}.d.ts`), ts);
  const py = join(pyOut, `${base.replaceAll("-", "_")}.py`);
  const tmp = join(mkdtempSync(join(tmpdir(), "nb-schema-")), file);
  writeFileSync(tmp, JSON.stringify(bundle(file)));
  execFileSync(
    "uv",
    [
      "run", "--project", "api", "datamodel-codegen",
      "--input", tmp, "--input-file-type", "jsonschema",
      "--output", py, "--output-model-type", "pydantic_v2.BaseModel",
      "--disable-timestamp",
    ],
    { cwd: root, stdio: "inherit" },
  );
}
writeFileSync(join(pyOut, "__init__.py"), "");
console.log(`generated ${files.length} schemas`);
