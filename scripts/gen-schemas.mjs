// Generate TypeScript types (web) and Pydantic models (api) from /shared/schemas.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "shared", "schemas");
const tsOut = join(root, "web", "src", "types", "generated");
const pyOut = join(root, "api", "app", "schemas", "generated");
mkdirSync(tsOut, { recursive: true });
mkdirSync(pyOut, { recursive: true });

const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json"));
for (const file of files) {
  const base = file.replace(".schema.json", "");
  const ts = await compileFromFile(join(schemaDir, file), { bannerComment: "/* Generated by `pnpm schemas`. Do not edit. */" });
  writeFileSync(join(tsOut, `${base}.d.ts`), ts);
  const py = join(pyOut, `${base.replaceAll("-", "_")}.py`);
  execFileSync(
    "uv",
    [
      "run", "--project", "api", "datamodel-codegen",
      "--input", join(schemaDir, file), "--input-file-type", "jsonschema",
      "--output", py, "--output-model-type", "pydantic_v2.BaseModel",
      "--disable-timestamp",
    ],
    { cwd: root, stdio: "inherit" },
  );
}
writeFileSync(join(pyOut, "__init__.py"), "");
console.log(`generated ${files.length} schemas`);
